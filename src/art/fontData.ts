export const FONT_CHARS = Object.keys(GLYPHS).join('');

/** Returns an 8x5 boolean matrix for a glyph. */
export function glyphRows(ch: string): boolean[][] {
  const src = GLYPHS[ch] ?? GLYPHS['?'];
  const rows = src.length ? src.split(' ') : [];
  const out: boolean[][] = [];
  for (let y = 0; y < GLYPH_H; y++) {
    const r = rows[y] ?? '.....';
    const row: boolean[] = [];
    for (let x = 0; x < GLYPH_W; x++) row.push(r[x] === '#');
    out.push(row);
  }
  return out;
}

/** Word-wraps text to a max number of characters per line (monospace font). */
export function wrapText(text: string, maxChars: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const w of words) {
      if (!line.length) line = w;
      else if ((line + ' ' + w).length <= maxChars) line += ' ' + w;
      else {
        out.push(line);
        line = w;
      }
      while (line.length > maxChars) {
        out.push(line.slice(0, maxChars));
        line = line.slice(maxChars);
      }
    }
    out.push(line);
  }
  return out;
}
